package reset

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
	"text/template"
)

const GeneratedFileName = "reset.gen.go"

type GenContext struct {
	SourceFile string
	PkgName    string
	Targets    []ResetTarget
}

var primitiveTypes = map[string]struct{}{
	"bool": {}, "string": {},
	"int": {}, "int8": {}, "int16": {}, "int32": {}, "int64": {},
	"uint": {}, "uint8": {}, "uint16": {}, "uint32": {}, "uint64": {}, "uintptr": {},
	"float32": {}, "float64": {},
	"complex64": {}, "complex128": {},
	"byte": {}, "rune": {},
	"any": {}, "error": {},
}

const resetTemplate = `// Code generated by reset. DO NOT EDIT.
// source: package {{.PkgName}}

package {{.PkgName}}

type Resettable interface {
	Reset()
}

{{range .Targets}}
// Reset сбрасывает состояние {{.TypeName}} к нулевым значениям.
func (x *{{.TypeName}}) Reset() {
if x == nil {
    return
}

{{- range .Fields}}
{{- if .Name}}
	{{resetExpr "x." .Name .TypeName}}
{{- end}}
{{- end}}
}
{{end}}
`

// GenerateResetFileForPackage generates a Go source file named "reset.gen.go"
func GenerateResetFileForPackage(dir, pkgName string, targets []ResetTarget) error {
	if len(targets) == 0 {
		return nil
	}

	outPath := filepath.Join(dir, GeneratedFileName)

	existing, err := os.ReadFile(outPath)
	switch {
	case err == nil:
		if !hasGeneratedMarker(existing) {
			return fmt.Errorf("%s: exists but has no generated marker, refusing to overwrite", outPath)
		}
	case errors.Is(err, fs.ErrNotExist):
	default:
		return fmt.Errorf("%s: read failed: %w", outPath, err)
	}

	rawCode, err := renderResetCode(pkgName, targets)
	if err != nil {
		return fmt.Errorf("render template: %w", err)
	}

	if err := writeFormattedFile(outPath, rawCode); err != nil {
		return fmt.Errorf("write file: %w", err)
	}

	return nil
}

func hasGeneratedMarker(data []byte) bool {
	const (
		prefix = "// Code generated by reset."
		suffix = "DO NOT EDIT."
	)
	for _, line := range bytes.Split(data, []byte("\n")) {
		s := strings.TrimSpace(string(line))
		if strings.HasPrefix(s, prefix) && strings.HasSuffix(s, suffix) {
			return true
		}
	}
	return false
}

func renderResetCode(pkgName string, targets []ResetTarget) ([]byte, error) {
	tmpl, err := template.New("reset").Funcs(template.FuncMap{
		"resetExpr": getResetExpression,
	}).Parse(resetTemplate)
	if err != nil {
		return nil, fmt.Errorf("parse template: %w", err)
	}

	var buf bytes.Buffer
	data := struct {
		PkgName string
		Targets []ResetTarget
	}{
		PkgName: pkgName,
		Targets: targets,
	}

	if err := tmpl.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("execute template: %w", err)
	}

	return buf.Bytes(), nil
}

func writeFormattedFile(path string, rawCode []byte) (err error) {
	formatted, err := format.Source(rawCode)
	if err != nil {
		return fmt.Errorf("format source: %w\n--- RAW OUTPUT ---\n%s", err, string(rawCode))
	}

	dir := filepath.Dir(path)
	tmp, err := os.CreateTemp(dir, GeneratedFileName+".tmp-*")
	if err != nil {
		return fmt.Errorf("create temp: %w", err)
	}
	tmpPath := tmp.Name()
	defer func() {
		if err != nil {
			os.Remove(tmpPath)
		}
	}()

	if _, err = tmp.Write(formatted); err != nil {
		tmp.Close()
		return fmt.Errorf("write temp: %w", err)
	}

	if err = tmp.Chmod(0o644); err != nil {
		tmp.Close()
		return fmt.Errorf("chmod temp: %w", err)
	}

	if err = tmp.Sync(); err != nil {
		tmp.Close()
		return fmt.Errorf("sync temp: %w", err)
	}
	if err = tmp.Close(); err != nil {
		return fmt.Errorf("close temp: %w", err)
	}

	if err = os.Rename(tmpPath, path); err != nil {
		return fmt.Errorf("rename temp: %w", err)
	}
	return nil
}

func getResetExpression(receiver, fieldName, typeName string) string {
	t := strings.TrimSpace(typeName)

	if strings.HasPrefix(t, "map[") {
		return fmt.Sprintf("clear(%s%s)", receiver, fieldName)
	}

	if after, ok := strings.CutPrefix(t, "[]"); ok {
		return handleSlice(receiver, fieldName, after)
	}

	if after, ok := strings.CutPrefix(t, "*"); ok {
		return handlePointer(receiver, fieldName, after)
	}

	if mightBeResettable(t) {
		return fmt.Sprintf(`if r, ok := any(&%s%s).(Resettable); ok {
			r.Reset()
		} else {
			%s%s = %s
		}`, receiver, fieldName, receiver, fieldName, getZeroValue(t))
	}

	return fmt.Sprintf("%s%s = %s", receiver, fieldName, getZeroValue(typeName))
}

func handlePointer(receiver, fieldName, baseType string) string {
	if mightBeResettable(baseType) {
		return fmt.Sprintf(`if r, ok := any(%s%s).(Resettable); ok {
				r.Reset()
			} else if %s%s != nil {
				*%s%s = %s
			}`, receiver, fieldName, receiver, fieldName, receiver, fieldName, getZeroValue(baseType))
	}

	return fmt.Sprintf(`if %s%s != nil {
			*%s%s = %s
		}`, receiver, fieldName, receiver, fieldName, getZeroValue(baseType))
}

func handleSlice(receiver, fieldName, elemType string) string {
	baseElem := elemType
	isPointerElem := false
	if strings.HasPrefix(elemType, "*") {
		isPointerElem = true
		baseElem = strings.TrimPrefix(elemType, "*")
	}

	if mightBeResettable(baseElem) {
		if isPointerElem {
			return fmt.Sprintf(`for i := range %s%s {
					if r, ok := any(%s%s[i]).(Resettable); ok {
						r.Reset()
					}
				}
				%s%s = %s%s[:0]`, receiver, fieldName, receiver, fieldName, receiver, fieldName, receiver, fieldName)
		}

		return fmt.Sprintf(`for i := range %s%s {
				if r, ok := any(&%s%s[i]).(Resettable); ok {
					r.Reset()
				}
			}
			%s%s = %s%s[:0]`, receiver, fieldName, receiver, fieldName, receiver, fieldName, receiver, fieldName)
	}

	return fmt.Sprintf("%s%s = %s%s[:0]", receiver, fieldName, receiver, fieldName)
}

func mightBeResettable(baseType string) bool {
	if strings.Contains(baseType, ".") {
		return false
	}
	_, isPrimitive := primitiveTypes[baseType]
	return !isPrimitive
}

func getZeroValue(typeName string) string {
	t := strings.TrimSpace(typeName)

	if len(t) == 0 {
		return ""
	}

	if strings.HasPrefix(t, "*") {
		return "nil"
	}

	if strings.HasPrefix(t, "chan ") ||
		strings.HasPrefix(t, "chan<- ") ||
		strings.HasPrefix(t, "<-chan ") {
		return "nil"
	}

	if strings.HasPrefix(t, "func(") {
		return "nil"
	}

	if t == "interface{}" || t == "any" || t == "error" ||
		strings.HasPrefix(t, "interface{") {
		return "nil"
	}

	switch t {
	case "string":
		return `""`
	case "bool":
		return "false"
	case "int", "int8", "int16", "int32", "int64",
		"uint", "uint8", "uint16", "uint32", "uint64", "uintptr",
		"float32", "float64",
		"complex64", "complex128",
		"byte", "rune":
		return "0"
	}

	return t + "{}"
}
